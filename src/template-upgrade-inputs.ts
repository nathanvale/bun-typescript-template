import { CliError } from "./cli-error.ts";
import { kernelPinFile, parseKernelPin } from "./kernel-pin.ts";
import { TEMPLATE_JSON_FILE } from "./recipe.ts";
import {
  decodeUtf8Strict,
  readCommittedBytes,
  readCommittedBytesAt,
  resolveTemplateCommit,
  verifyGitRepository,
  verifyTemplateAncestry,
} from "./template-upgrade-git.ts";

export const OLD_TEMPLATE_JSON_FILE = ".cli-design-template.json";
const PACKAGE_FILE = "package.json";
const KERNEL_PACKAGE_NAME = "agent-cli-kernel";
const FULL_COMMIT_PATTERN = /^[0-9a-f]{40}$/;
const KERNEL_PIN_SPECIFIER_PATTERN = /^[^#]+#([0-9a-f]{40})$/;

export interface TemplateUpgradeInputs {
  readonly templateRoot: string;
  readonly repository: string;
  readonly repositoryHead: string;
  readonly baseCommit: string;
  readonly targetCommit: string;
  readonly repositoryName: string;
  readonly sourcePacket: string;
  readonly repositoryPinnedCommit: string;
  readonly templatePinnedCommit: string;
}

export interface TemplateUpgradeInputRequest {
  readonly templateRoot: string;
  readonly repository: string;
  readonly targetRef: string;
  readonly env: Readonly<Record<string, string | undefined>>;
}

function parseJsonObject(
  bytes: Uint8Array,
  label: string,
  code: string,
  repair: string,
): Map<string, unknown> {
  const text = decodeUtf8Strict(bytes, label);
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new CliError(code, `${label} is not valid JSON`, repair, 1, false);
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new CliError(
      code,
      `${label} must be a JSON object`,
      repair,
      1,
      false,
    );
  }
  return new Map(Object.entries(parsed));
}

interface CommittedStamp {
  readonly stampFile: string;
  readonly fields: Map<string, unknown>;
}

function readStampFields(
  repository: string,
  env: Readonly<Record<string, string | undefined>>,
): CommittedStamp {
  const currentBytes = readCommittedBytes(repository, TEMPLATE_JSON_FILE, env);
  const oldBytes = readCommittedBytes(repository, OLD_TEMPLATE_JSON_FILE, env);
  if (currentBytes !== undefined && oldBytes !== undefined) {
    throw new CliError(
      "stamp_duplicate",
      `${repository} has both committed ${TEMPLATE_JSON_FILE} and ${OLD_TEMPLATE_JSON_FILE} at HEAD`,
      `delete ${OLD_TEMPLATE_JSON_FILE} in ${repository} and commit the removal so only ${TEMPLATE_JSON_FILE} remains`,
      2,
      true,
    );
  }
  const stampFile =
    currentBytes !== undefined ? TEMPLATE_JSON_FILE : OLD_TEMPLATE_JSON_FILE;
  const bytes = currentBytes ?? oldBytes;
  if (bytes === undefined) {
    throw new CliError(
      "stamp_missing",
      `${repository} has no committed ${TEMPLATE_JSON_FILE} at HEAD`,
      `commit ${TEMPLATE_JSON_FILE} in ${repository}, or run upgrade on a repository generated by this template`,
      2,
      true,
    );
  }
  return {
    stampFile,
    fields: parseJsonObject(
      bytes,
      `HEAD:${stampFile}`,
      "stamp_invalid",
      `restore a valid ${stampFile} commit in ${repository}`,
    ),
  };
}

function readCommittedRepositoryName(
  stampFile: string,
  stampFields: ReadonlyMap<string, unknown>,
  packageFields: ReadonlyMap<string, unknown> | undefined,
): string {
  const stampName = stampFields.get("name");
  if (typeof stampName === "string" && stampName.trim() !== "") {
    return stampName;
  }
  if (packageFields === undefined) {
    throw new CliError(
      "repository_name_missing",
      `cannot determine repository name: HEAD:${stampFile} has no name and HEAD:${PACKAGE_FILE} is missing`,
      `add a non-empty "name" to ${PACKAGE_FILE} or ${stampFile} and commit it`,
      2,
      true,
    );
  }
  const packageName = packageFields.get("name");
  if (typeof packageName !== "string" || packageName.trim() === "") {
    throw new CliError(
      "repository_name_missing",
      `HEAD:${PACKAGE_FILE} does not have a non-empty string "name"`,
      `set a non-empty "name" in ${PACKAGE_FILE} and commit it`,
      2,
      true,
    );
  }
  return packageName;
}

function readRepositoryPinnedCommit(
  repository: string,
  packageFields: ReadonlyMap<string, unknown> | undefined,
): string {
  if (packageFields === undefined) {
    throw new CliError(
      "repository_pin_missing",
      `${repository} has no committed ${PACKAGE_FILE} at HEAD, so its kernel Pin cannot be read`,
      `commit ${PACKAGE_FILE} with "${KERNEL_PACKAGE_NAME}" pinned to a full 40-character commit (#<40-hex>)`,
      2,
      true,
    );
  }
  const dependencies = packageFields.get("dependencies");
  const dependencyMap =
    typeof dependencies === "object" &&
    dependencies !== null &&
    !Array.isArray(dependencies)
      ? new Map<string, unknown>(Object.entries(dependencies))
      : undefined;
  const specifier = dependencyMap?.get(KERNEL_PACKAGE_NAME);
  if (specifier === undefined) {
    throw new CliError(
      "repository_pin_missing",
      `HEAD:${PACKAGE_FILE} has no dependencies.${KERNEL_PACKAGE_NAME} Pin`,
      `add "${KERNEL_PACKAGE_NAME}" pinned to a full 40-character commit (#<40-hex>) in ${PACKAGE_FILE} and commit it`,
      2,
      true,
    );
  }
  const match =
    typeof specifier === "string"
      ? KERNEL_PIN_SPECIFIER_PATTERN.exec(specifier)
      : null;
  if (match?.[1] === undefined) {
    throw new CliError(
      "repository_pin_invalid",
      `HEAD:${PACKAGE_FILE} dependency "${KERNEL_PACKAGE_NAME}" (${JSON.stringify(specifier)}) is not pinned to a full 40-character commit`,
      `pin "${KERNEL_PACKAGE_NAME}" to a full 40-character commit (#<40-hex>) in ${PACKAGE_FILE} and commit it`,
      2,
      true,
    );
  }
  return match[1];
}

function readTemplatePinnedCommit(
  templateRoot: string,
  targetCommit: string,
  env: Readonly<Record<string, string | undefined>>,
): string {
  const bytes = readCommittedBytesAt(
    templateRoot,
    targetCommit,
    kernelPinFile,
    env,
  );
  if (bytes === undefined) {
    throw new CliError(
      "template_pin_missing",
      `template commit ${targetCommit.slice(0, 7)} has no ${kernelPinFile}`,
      `verify ${kernelPinFile} exists at template commit ${targetCommit.slice(0, 7)}`,
      1,
      false,
    );
  }
  const text = decodeUtf8Strict(
    bytes,
    `${targetCommit.slice(0, 7)}:${kernelPinFile}`,
  );
  try {
    return parseKernelPin(text).commit;
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new CliError(
      "template_pin_invalid",
      `template commit ${targetCommit.slice(0, 7)} has an invalid ${kernelPinFile}: ${detail}`,
      `restore a valid ${kernelPinFile} at template commit ${targetCommit.slice(0, 7)}`,
      1,
      false,
    );
  }
}

function readCommittedPackageFields(
  repository: string,
  stampFields: ReadonlyMap<string, unknown>,
  env: Readonly<Record<string, string | undefined>>,
): Map<string, unknown> | undefined {
  const packageBytes = readCommittedBytes(repository, PACKAGE_FILE, env);
  if (packageBytes === undefined) {
    return undefined;
  }
  const stampName = stampFields.get("name");
  const needsPackageName =
    typeof stampName !== "string" || stampName.trim() === "";
  return parseJsonObject(
    packageBytes,
    `HEAD:${PACKAGE_FILE}`,
    needsPackageName ? "repository_name_missing" : "repository_pin_invalid",
    needsPackageName
      ? `fix HEAD:${PACKAGE_FILE} so it is a valid JSON object with a non-empty "name"`
      : `fix HEAD:${PACKAGE_FILE} so it is a valid JSON object with a pinned "${KERNEL_PACKAGE_NAME}" dependency`,
  );
}

export function resolveTemplateUpgradeInputs(
  request: TemplateUpgradeInputRequest,
): TemplateUpgradeInputs {
  const { templateRoot, repository, targetRef, env } = request;
  const repositoryHead = verifyGitRepository(repository, env);
  const { stampFile, fields: stampFields } = readStampFields(repository, env);

  const templateDirty = stampFields.get("templateDirty");
  if (templateDirty === true) {
    throw new CliError(
      "template_dirty",
      `HEAD:${stampFile} has templateDirty: true, so its base state cannot be reproduced`,
      "regenerate the repository from a clean template commit before upgrading",
      2,
      true,
    );
  }

  const baseCommit = stampFields.get("templateRevision");
  if (typeof baseCommit !== "string" || !FULL_COMMIT_PATTERN.test(baseCommit)) {
    throw new CliError(
      "stamp_invalid",
      `HEAD:${stampFile} has an invalid templateRevision`,
      `record a full 40-character template commit in ${stampFile}`,
      2,
      true,
    );
  }

  const sourcePacket = stampFields.get("sourcePacket");
  if (typeof sourcePacket !== "string" || sourcePacket.trim() === "") {
    throw new CliError(
      "stamp_invalid",
      `HEAD:${stampFile} has a missing or empty sourcePacket`,
      `record the repository's sourcePacket in ${stampFile}`,
      2,
      true,
    );
  }

  const targetCommit = resolveTemplateCommit(templateRoot, targetRef, env);
  verifyTemplateAncestry(templateRoot, baseCommit, targetCommit, env);
  const packageFields = readCommittedPackageFields(
    repository,
    stampFields,
    env,
  );
  const repositoryName = readCommittedRepositoryName(
    stampFile,
    stampFields,
    packageFields,
  );
  const repositoryPinnedCommit = readRepositoryPinnedCommit(
    repository,
    packageFields,
  );
  const templatePinnedCommit = readTemplatePinnedCommit(
    templateRoot,
    targetCommit,
    env,
  );

  return Object.freeze({
    templateRoot,
    repository,
    repositoryHead,
    baseCommit,
    targetCommit,
    repositoryName,
    sourcePacket,
    repositoryPinnedCommit,
    templatePinnedCommit,
  });
}
