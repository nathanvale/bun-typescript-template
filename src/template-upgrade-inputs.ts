import { CliError } from "./cli-error.ts";
import {
  decodeUtf8Strict,
  readCommittedBytes,
  resolveTemplateCommit,
  verifyGitRepository,
  verifyTemplateAncestry,
} from "./template-upgrade-git.ts";

const STAMP_FILE = ".cli-design-template.json";
const PACKAGE_FILE = "package.json";
const FULL_COMMIT_PATTERN = /^[0-9a-f]{40}$/;

export interface TemplateUpgradeInputs {
  readonly templateRoot: string;
  readonly repository: string;
  readonly repositoryHead: string;
  readonly baseCommit: string;
  readonly targetCommit: string;
  readonly repositoryName: string;
  readonly sourcePacket: string;
}

export interface TemplateUpgradeInputRequest {
  readonly templateRoot: string;
  readonly repository: string;
  readonly targetRef: string;
  readonly env: Readonly<Record<string, string | undefined>>;
}

function parseJsonObject(
  bytes: Uint8Array,
  label: string,
  code: string,
  repair: string,
): Map<string, unknown> {
  const text = decodeUtf8Strict(bytes, label);
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new CliError(code, `${label} is not valid JSON`, repair, 1, false);
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new CliError(
      code,
      `${label} must be a JSON object`,
      repair,
      1,
      false,
    );
  }
  return new Map(Object.entries(parsed));
}

function readStampFields(
  repository: string,
  env: Readonly<Record<string, string | undefined>>,
): Map<string, unknown> {
  const bytes = readCommittedBytes(repository, STAMP_FILE, env);
  if (bytes === undefined) {
    throw new CliError(
      "stamp_missing",
      `${repository} has no committed ${STAMP_FILE} at HEAD`,
      `commit ${STAMP_FILE} in ${repository}, or run upgrade on a repository generated by this template`,
      2,
      true,
    );
  }
  return parseJsonObject(
    bytes,
    `HEAD:${STAMP_FILE}`,
    "stamp_invalid",
    `restore a valid ${STAMP_FILE} commit in ${repository}`,
  );
}

function readCommittedRepositoryName(
  repository: string,
  stampFields: ReadonlyMap<string, unknown>,
  env: Readonly<Record<string, string | undefined>>,
): string {
  const stampName = stampFields.get("name");
  if (typeof stampName === "string" && stampName.trim() !== "") {
    return stampName;
  }
  const packageBytes = readCommittedBytes(repository, PACKAGE_FILE, env);
  if (packageBytes === undefined) {
    throw new CliError(
      "repository_name_missing",
      `cannot determine repository name: HEAD:${STAMP_FILE} has no name and HEAD:${PACKAGE_FILE} is missing`,
      `add a non-empty "name" to ${PACKAGE_FILE} or ${STAMP_FILE} and commit it`,
      2,
      true,
    );
  }
  const packageFields = parseJsonObject(
    packageBytes,
    `HEAD:${PACKAGE_FILE}`,
    "repository_name_missing",
    `fix HEAD:${PACKAGE_FILE} so it is a valid JSON object with a non-empty "name"`,
  );
  const packageName = packageFields.get("name");
  if (typeof packageName !== "string" || packageName.trim() === "") {
    throw new CliError(
      "repository_name_missing",
      `HEAD:${PACKAGE_FILE} does not have a non-empty string "name"`,
      `set a non-empty "name" in ${PACKAGE_FILE} and commit it`,
      2,
      true,
    );
  }
  return packageName;
}

export function resolveTemplateUpgradeInputs(
  request: TemplateUpgradeInputRequest,
): TemplateUpgradeInputs {
  const { templateRoot, repository, targetRef, env } = request;
  const repositoryHead = verifyGitRepository(repository, env);
  const stampFields = readStampFields(repository, env);

  const templateDirty = stampFields.get("templateDirty");
  if (templateDirty === true) {
    throw new CliError(
      "template_dirty",
      `HEAD:${STAMP_FILE} has templateDirty: true, so its base state cannot be reproduced`,
      "regenerate the repository from a clean template commit before upgrading",
      2,
      true,
    );
  }

  const baseCommit = stampFields.get("templateRevision");
  if (typeof baseCommit !== "string" || !FULL_COMMIT_PATTERN.test(baseCommit)) {
    throw new CliError(
      "stamp_invalid",
      `HEAD:${STAMP_FILE} has an invalid templateRevision`,
      `record a full 40-character template commit in ${STAMP_FILE}`,
      2,
      true,
    );
  }

  const sourcePacket = stampFields.get("sourcePacket");
  if (typeof sourcePacket !== "string" || sourcePacket.trim() === "") {
    throw new CliError(
      "stamp_invalid",
      `HEAD:${STAMP_FILE} has a missing or empty sourcePacket`,
      `record the repository's sourcePacket in ${STAMP_FILE}`,
      2,
      true,
    );
  }

  const repositoryName = readCommittedRepositoryName(
    repository,
    stampFields,
    env,
  );
  const targetCommit = resolveTemplateCommit(templateRoot, targetRef, env);
  verifyTemplateAncestry(templateRoot, baseCommit, targetCommit, env);

  return Object.freeze({
    templateRoot,
    repository,
    repositoryHead,
    baseCommit,
    targetCommit,
    repositoryName,
    sourcePacket,
  });
}
